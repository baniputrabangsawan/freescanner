package com.freescanner.printing

import android.os.Bundle
import android.os.CancellationSignal
import android.os.Handler
import android.os.Looper
import android.os.ParcelFileDescriptor
import android.print.PageRange
import android.print.PrintAttributes
import android.print.PrintDocumentAdapter
import android.print.PrintDocumentInfo
import com.tom_roush.pdfbox.io.MemoryUsageSetting
import com.tom_roush.pdfbox.pdmodel.PDDocument
import java.io.File
import java.io.IOException
import java.util.concurrent.Executors
import java.util.concurrent.RejectedExecutionException

/** Input must be an unprotected PDF freshly generated by DocumentExporter, never an import URI. */
class PdfPrintAdapter(private val file: File, private val title: String, private val pageCount: Int) : PrintDocumentAdapter() {
    private val worker = Executors.newSingleThreadExecutor()
    private val main = Handler(Looper.getMainLooper())

    override fun onLayout(oldAttributes: PrintAttributes?, newAttributes: PrintAttributes, cancellationSignal: CancellationSignal,
        callback: LayoutResultCallback, extras: Bundle?) {
        if (cancellationSignal.isCanceled) { callback.onLayoutCancelled(); return }
        if (pageCount <= 0 || !file.isFile || file.length() == 0L) {
            callback.onLayoutFailed("Dokumen cetak ini tidak lagi tersedia. Siapkan kembali.")
            return
        }
        callback.onLayoutFinished(PrintDocumentInfo.Builder(title.ifBlank { "Dokumen" })
            .setContentType(PrintDocumentInfo.CONTENT_TYPE_DOCUMENT).setPageCount(pageCount).build(), oldAttributes != newAttributes)
    }

    override fun onWrite(pages: Array<out PageRange>, destination: ParcelFileDescriptor, cancellationSignal: CancellationSignal, callback: WriteResultCallback) {
        try {
            worker.execute {
                try {
                    cancellationSignal.throwIfCanceled()
                    val indices = selectedIndices(pages, pageCount)
                    if (indices.isEmpty()) throw IOException("Tidak ada halaman yang diminta tersedia untuk dicetak.")
                    ParcelFileDescriptor.AutoCloseOutputStream(destination).use { output ->
                        writeSelected(file, pageCount, indices, output, cancellationSignal)
                    }
                    main.post {
                        if (cancellationSignal.isCanceled) callback.onWriteCancelled()
                        else callback.onWriteFinished(compactRanges(indices))
                    }
                } catch (_: android.os.OperationCanceledException) {
                    closeQuietly(destination)
                    main.post { callback.onWriteCancelled() }
                } catch (_: Exception) {
                    closeQuietly(destination)
                    main.post {
                        if (cancellationSignal.isCanceled) callback.onWriteCancelled()
                        else callback.onWriteFailed("Tidak dapat menyiapkan halaman PDF yang dipilih untuk dicetak. Ekspor PDF tanpa perlindungan dan coba lagi.")
                    }
                }
            }
        } catch (_: RejectedExecutionException) {
            closeQuietly(destination)
            callback.onWriteCancelled()
        }
    }

    override fun onFinish() { worker.shutdown() }

    private fun closeQuietly(descriptor: ParcelFileDescriptor) {
        try { descriptor.close() } catch (_: IOException) { /* Already closed by the output stream. */ }
    }

    companion object {
        /** Shared by the adapter and fixture tests; caller owns the output stream. */
        internal fun writeSelected(file: File, count: Int, indices: List<Int>, output: java.io.OutputStream, signal: CancellationSignal) {
            require(indices.isNotEmpty() && indices.all { it in 0 until count }) { "Pilih halaman yang valid untuk dicetak." }
            signal.throwIfCanceled()
            PDDocument.load(file, MemoryUsageSetting.setupTempFileOnly().setTempDir(file.parentFile)).use { source ->
                if (source.isEncrypted) throw IOException("Siapkan PDF tanpa perlindungan untuk dicetak melalui Android.")
                if (source.numberOfPages != count) throw IOException("Dokumen cetak berubah. Siapkan kembali.")
                PDDocument(MemoryUsageSetting.setupTempFileOnly().setTempDir(file.parentFile)).use { selected ->
                    indices.forEach { index ->
                        signal.throwIfCanceled()
                        val original = source.getPage(index)
                        selected.importPage(original).resources = original.resources
                    }
                    val checked = object : java.io.FilterOutputStream(output) {
                        override fun write(value: Int) { signal.throwIfCanceled(); out.write(value) }
                        override fun write(bytes: ByteArray, offset: Int, length: Int) {
                            signal.throwIfCanceled(); out.write(bytes, offset, length)
                        }
                    }
                    signal.throwIfCanceled()
                    selected.save(checked)
                    checked.flush()
                    signal.throwIfCanceled()
                }
            }
        }

        internal fun selectedIndices(ranges: Array<out PageRange>, count: Int): List<Int> {
            require(count > 0) { "Dokumen cetak tidak memiliki halaman." }
            return (0 until count).filter { index -> ranges.any { index >= it.start && index <= it.end } }
        }

        internal fun compactRanges(indices: List<Int>): Array<PageRange> {
            if (indices.isEmpty()) return emptyArray()
            val ranges = mutableListOf<PageRange>()
            var first = indices.first()
            var last = first
            for (index in indices.drop(1)) {
                if (index == last + 1) last = index else {
                    ranges += PageRange(first, last)
                    first = index
                    last = index
                }
            }
            ranges += PageRange(first, last)
            return ranges.toTypedArray()
        }
    }
}
